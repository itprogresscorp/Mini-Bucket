define('ROOT_PATH', dirname(dirname(__FILE__)));

if (file_exists(ROOT_PATH . '/config.php')) {
    require_once ROOT_PATH . '/config.php';
}

header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Methods: GET, POST, PUT, DELETE, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, X-API-Key, Authorization, X-Requested-With");
header("Access-Control-Allow-Credentials: true");
header("Access-Control-Max-Age: 86400");

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(200);
    exit();
}


header('Content-Type: application/json');


function validateApiKey() {
    global $db;
    
    if (!$db) {
        try {
            $db = getDB();
        } catch (Exception $e) {
            http_response_code(500);
            echo json_encode(['error' => 'Database connection failed']);
            exit;
        }
    }
    
    $headers = function_exists('getallheaders') ? getallheaders() : [];
    $apiKey = $headers['X-API-Key'] ?? $_GET['api_key'] ?? $_SERVER['HTTP_X_API_KEY'] ?? '';
    
    if (empty($apiKey)) {
        if (isset($_SESSION['user_id'])) {
            return true;
        }
        http_response_code(401);
        echo json_encode(['error' => 'API key required']);
        exit;
    }
    
    $stmt = $db->prepare("SELECT idHost, hostName FROM hosts WHERE hostApiKey = :key");
    $stmt->bindValue(':key', $apiKey, SQLITE3_TEXT);
    $result = $stmt->execute();
    $host = $result->fetchArray(SQLITE3_ASSOC);
    
    if (!$host) {
        http_response_code(403);
        echo json_encode(['error' => 'Invalid API key']);
        exit;
    }
    
    return true;
}

validateApiKey();

$path = $_GET['path'] ?? '';

if (empty($path)) {
    echo json_encode(['success' => false, 'error' => 'No path provided']);
    exit;
}

if (!file_exists($path)) {
    echo json_encode(['success' => false, 'error' => 'Path does not exist']);
    exit;
}

$df = shell_exec("df -h --output=size,used,avail,pcent " . escapeshellarg($path) . " 2>/dev/null | tail -1");
if (!$df || trim($df) === '') {
    echo json_encode(['success' => false, 'error' => 'Cannot get disk usage']);
    exit;
}

$parts = preg_split('/\s+/', trim($df));
if (count($parts) >= 4) {
    echo json_encode([
        'success' => true,
        'size' => $parts[0] ?? '?',
        'used' => $parts[1] ?? '?',
        'avail' => $parts[2] ?? '?',
        'percent' => intval(rtrim($parts[3], '%')) ?? 0
    ]);
} else {
    echo json_encode(['success' => false, 'error' => 'Invalid df output']);
}
